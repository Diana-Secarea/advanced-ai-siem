_page = [0]  # running slide counter for footers


def add_slide(accent=CYAN, footer=True):
    _page[0] += 1
    s = prs.slides.add_slide(BLANK)
    s.background.fill.solid()
    s.background.fill.fore_color.rgb = BG
    # left accent bar
    bar = s.shapes.add_shape(1, 0, 0, Inches(0.14), SLIDE_H)
    bar.fill.solid(); bar.fill.fore_color.rgb = accent
    bar.line.fill.background()
    # bottom hairline
    hl = s.shapes.add_shape(1, Inches(0.14), SLIDE_H - Emu(19050), SLIDE_W, Emu(19050))
    hl.fill.solid(); hl.fill.fore_color.rgb = PANEL
    hl.line.fill.background()
    if footer:
        # name bottom-left, slide number bottom-right
        fl = s.shapes.add_textbox(Inches(0.5), SLIDE_H - Inches(0.42), Inches(6), Inches(0.32))
        p = fl.text_frame.paragraphs[0]; r = p.add_run()
        r.text = "AI Threat Engine · Diana Maria Secarea"
        r.font.size = Pt(9); r.font.color.rgb = TEXT_DIM
        fr = s.shapes.add_textbox(SLIDE_W - Inches(1.3), SLIDE_H - Inches(0.42), Inches(0.9), Inches(0.32))
        p2 = fr.text_frame.paragraphs[0]; p2.alignment = PP_ALIGN.RIGHT
        r2 = p2.add_run(); r2.text = str(_page[0]).zfill(2)
        r2.font.size = Pt(9); r2.font.color.rgb = accent; r2.font.bold = True
    return s


def divider(main, accent, kicker, num):
    """Full-bleed section divider slide."""
    s = add_slide(accent, footer=False)
    band = s.shapes.add_shape(1, 0, 0, Inches(0.14), SLIDE_H)
    band.fill.solid(); band.fill.fore_color.rgb = accent; band.line.fill.background()
    txt(s, Inches(1.0), Inches(2.5), Inches(2.4), Inches(1.6),
        [(num, accent, True)], size=90)
    tb = s.shapes.add_textbox(Inches(3.4), Inches(2.75), Inches(9.0), Inches(2.2))
    tf = tb.text_frame; tf.word_wrap = True
    p0 = tf.paragraphs[0]; r0 = p0.add_run(); r0.text = kicker
    r0.font.size = Pt(15); r0.font.color.rgb = SOFT; r0.font.name = "Segoe UI"
    p1 = tf.add_paragraph(); r1 = p1.add_run(); r1.text = main
    r1.font.size = Pt(46); r1.font.bold = True; r1.font.color.rgb = TEXT; r1.font.name = "Segoe UI"
    return s


def txt(slide, x, y, w, h, runs, size=18, bold=False, color=TEXT,
        align=PP_ALIGN.LEFT, font="Segoe UI", spacing=1.0):
    """runs: str OR list of (text, color, bold) tuples for one paragraph each."""
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    if isinstance(runs, str):
        runs = [(runs, color, bold)]
    for i, item in enumerate(runs):
        t, c, b = item if isinstance(item, tuple) else (item, color, bold)
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = spacing
        r = p.add_run(); r.text = t
        r.font.size = Pt(size); r.font.bold = b
        r.font.color.rgb = c; r.font.name = font
    return tb


def bullets(slide, x, y, w, h, items, size=16, gap=6):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame; tf.word_wrap = True
    for i, item in enumerate(items):
        head, body, col = item
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap); p.line_spacing = 1.08
        r = p.add_run(); r.text = "▸ "
        r.font.size = Pt(size); r.font.color.rgb = col; r.font.bold = True
        r2 = p.add_run(); r2.text = head
        r2.font.size = Pt(size); r2.font.color.rgb = col; r2.font.bold = True
        if body:
            r3 = p.add_run(); r3.text = " — " + body
            r3.font.size = Pt(size); r3.font.color.rgb = TEXT
    return tb


def title(slide, main, accent_word=None, accent=CYAN, sub=None):
    tb = slide.shapes.add_textbox(Inches(0.55), Inches(0.32), Inches(12.3), Inches(1.1))
    tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]
    r = p.add_run(); r.text = main + (" " if accent_word else "")
    r.font.size = Pt(32); r.font.bold = True; r.font.color.rgb = TEXT
    r.font.name = "Segoe UI"
    if accent_word:
        r2 = p.add_run(); r2.text = accent_word
        r2.font.size = Pt(32); r2.font.bold = True; r2.font.color.rgb = accent
        r2.font.name = "Segoe UI"
    if sub:
        p2 = tf.add_paragraph()
        r3 = p2.add_run(); r3.text = sub
        r3.font.size = Pt(14); r3.font.color.rgb = SOFT; r3.font.italic = True


def chip(slide, x, y, text, color, size=12):
    w = Inches(0.28 + len(text) * 0.085)
    sh = slide.shapes.add_shape(9, x, y, w, Inches(0.42))  # rounded rect
    sh.fill.solid(); sh.fill.fore_color.rgb = PANEL
    sh.line.color.rgb = color; sh.line.width = Pt(1.4)
    tf = sh.text_frame; tf.word_wrap = False
    p = tf.paragraphs[0]; p.alignment = PP_ALIGN.CENTER
    r = p.add_run(); r.text = text
    r.font.size = Pt(size); r.font.bold = True; r.font.color.rgb = color
    return x + w + Inches(0.18)


def pic(slide, name, x, y, w=None, h=None):
    return slide.shapes.add_picture(os.path.join(IMG, name), x, y, width=w, height=h)


def notes(slide, text):
    slide.notes_slide.notes_text_frame.text = text


