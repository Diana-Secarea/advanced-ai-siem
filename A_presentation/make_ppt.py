from pptx.oxml.ns import qn

def add_fade(slide, spd="med"):
    sld = slide._element
    for ex in sld.findall(qn("p:transition")):
        sld.remove(ex)
    trans = sld.makeelement(qn("p:transition"), {"spd": spd})
    trans.append(trans.makeelement(qn("p:fade"), {}))
    ref = sld.find(qn("p:clrMapOvr"))
    if ref is None:
        ref = sld.find(qn("p:cSld"))
    ref.addnext(trans)

for _sl in prs.slides:
    add_fade(_sl, spd="med")

