def simple_table(slide, x, y, w, headers, rows, col_widths, accent=CYAN, row_h=0.52, fs=12):
    """Lightweight table drawn with a python-pptx GraphicFrame."""
    from pptx.util import Inches as _In
    n_rows = len(rows) + 1
    tbl_shape = slide.shapes.add_table(n_rows, len(headers), x, y, w, _In(row_h * n_rows))
    tbl = tbl_shape.table
    for j, cw in enumerate(col_widths):
        tbl.columns[j].width = _In(cw)
    for j, h in enumerate(headers):
        c = tbl.cell(0, j)
        c.fill.solid(); c.fill.fore_color.rgb = PANEL
        p = c.text_frame.paragraphs[0]; r = p.add_run(); r.text = h
        r.font.size = Pt(fs); r.font.bold = True; r.font.color.rgb = accent
    for i, row in enumerate(rows, 1):
        for j, val in enumerate(row):
            c = tbl.cell(i, j)
            c.fill.solid(); c.fill.fore_color.rgb = BG
            p = c.text_frame.paragraphs[0]; r = p.add_run(); r.text = str(val)
            r.font.size = Pt(fs - 0.5)
            r.font.color.rgb = TEXT if j == 0 else SOFT
            if j == 0:
                r.font.bold = True
    return tbl_shape


